#!/usr/bin/env python3
"""构建最终 Magisk 修复模块：
  A) /vendor/etc/media_codecs_oplus_c2.xml   (新增, 注册 Codec2 软件音频编解码器)
  B) /vendor/etc/media_codecs_google_audio.xml (移除失效的 OMX 软件 AAC 编码器)
  C) /vendor/etc/media_codecs.xml            (追加 Include c2 音频配置)
"""
import os, re, shutil, xml.dom.minidom

SRC = "/tmp/codecfix"
OUT = "/tmp/codecfix/module"
VENDOR = os.path.join(OUT, "system/vendor/etc")

shutil.rmtree(OUT, ignore_errors=True)
os.makedirs(VENDOR)

# ---------- A) media_codecs_oplus_c2.xml ----------
c2 = open(os.path.join(SRC, "media_codecs_google_c2_audio.xml"), encoding="utf-8").read()
body = c2.split("<Included>", 1)[1].rsplit("</Included>", 1)[0]
# 给 AAC 编码器加 rank，确保优先于任何残留的 OMX 条目
body = body.replace(
    '<MediaCodec name="c2.android.aac.encoder" type="audio/mp4a-latm">',
    '<MediaCodec name="c2.android.aac.encoder" type="audio/mp4a-latm" rank="512">')
assert 'rank="512"' in body
new_c2 = (
    '<?xml version="1.0" encoding="utf-8" ?>\n'
    '<!-- Codec2 software audio codecs (auto-generated by WorkBuddy)\n'
    '     Registers c2.android.* audio decoders/encoders so that MediaRecorder\n'
    '     can create an AAC audio encoder (fixes "cannot save video"). -->\n'
    '<Included>' + body + '</Included>\n')
open(os.path.join(VENDOR, "media_codecs_oplus_c2.xml"), "w", encoding="utf-8").write(new_c2)
xml.dom.minidom.parseString(new_c2)
print("[A] media_codecs_oplus_c2.xml  %d bytes" % len(new_c2))

# ---------- B) media_codecs_google_audio.xml ----------
t = open(os.path.join(SRC, "media_codecs_google_audio.xml"), encoding="utf-8").read()
pat = re.compile(r'[ \t]*<MediaCodec name="OMX\.google\.aac\.encoder".*?</MediaCodec>\s*\n', re.S)
assert pat.search(t)
t2 = pat.sub("", t, count=1)
assert "OMX.google.aac.encoder" not in t2
xml.dom.minidom.parseString(t2)
open(os.path.join(VENDOR, "media_codecs_google_audio.xml"), "w", encoding="utf-8").write(t2)
print("[B] media_codecs_google_audio.xml  %d bytes (移除 OMX AAC 编码器)" % len(t2))

# ---------- C) media_codecs.xml ----------
m = open(os.path.join(SRC, "media_codecs.xml"), encoding="utf-8").read()
anchor = '    <Include href="media_codecs_google_audio.xml" />'
assert m.count(anchor) == 1
m2 = m.replace(anchor, anchor +
    '\n    <!-- Codec2 software audio codecs -->'
    '\n    <Include href="media_codecs_google_c2_audio.xml" />')
xml.dom.minidom.parseString(m2)
open(os.path.join(VENDOR, "media_codecs.xml"), "w", encoding="utf-8").write(m2)
print("[C] media_codecs.xml  %d bytes (追加 c2 音频 Include)" % len(m2))

# ---------- module.prop / README ----------
open(os.path.join(OUT, "module.prop"), "w", encoding="utf-8").write(
"""id=codec2audiofix
name=Codec2 Audio Fix (A16 port)
version=2.0
versionCode=2
author=WorkBuddy
description=注册 Codec2 软件音频编解码器(AAC 等),修复相机录像无法保存与音频解码失败
""")
open(os.path.join(OUT, "README.txt"), "w", encoding="utf-8").write(
"""Codec2 Audio Fix v2 —— 修复「相机录像无法保存视频」

【根因】
ColorOS 16 的框架把 Codec2(c2.*) 软件编解码器交给 Codec2InfoBuilder 注册,
它只从 media_codecs_c2.xml / media_codecs_oplus_c2.xml 这类文件里读取声明。
本机 /vendor/etc 下这两个文件都不存在(ODM 里只有旧命名的 media_codecs_c2.xml),
于是 c2.android.aac.encoder 根本没注册;而传统 OMX 软件 AAC 编码器
(OMX.google.aac.encoder) 又无法实例化,结果 MediaRecorder 在
"Failed to create audio encoder" 处失败 -> 录像无法保存。

【本模块做三件事(全部为叠加,不删除分区文件)】
  A 新增 /vendor/etc/media_codecs_oplus_c2.xml
    注册 c2.android.aac/amr/mp3/opus/vorbis/flac/raw 等软件音频编解码器
  B 覆盖 /vendor/etc/media_codecs_google_audio.xml
    移除失效的 OMX.google.aac.encoder 条目,避免它被优先选中
  C 覆盖 /vendor/etc/media_codecs.xml
    追加 <Include href="media_codecs_google_c2_audio.xml" /> 作为冗余路径

【效果】
  - 相机录像(含声音)可正常保存
  - AAC/MP3/Opus/Vorbis/FLAC/AMR 等音频解码改由 Codec2 软件实现,播放更可靠

【卸载】Magisk 中删除本模块后重启,完全恢复原状。
""")
print("[ok] module.prop / README.txt 已生成")
